const normalizeServiceName = (value: string) =>
  value
    .trim()
    .toLocaleLowerCase()
    .replace(/&/g, 'and')
    .replace(/\bservices?\b/g, '')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();

export function suggestedServiceImage(
  serviceName: string,
): ServiceImageOption | undefined {
  const normalizedName = normalizeServiceName(serviceName);
  if (!normalizedName) return undefined;

  return SERVICE_IMAGE_OPTIONS.find(
    (option) => normalizeServiceName(option.serviceName) === normalizedName,
  );
}
